import { z } from "zod";

import { DEFAULT_LOCALE, LOCALES } from "@/shared/i18n/locales";

import { areaSchema } from "./area";

// Mirror the database checks (catalogKey and emergencies_slug_check) so the form explains them.
export const KEY_PATTERN = /^[a-z][a-z0-9_]{1,39}$/;
export const SLUG_PATTERN = /^[a-z0-9]+(-[a-z0-9]+)*$/;
const SLUG_MAX = 60;
const NAME_MAX = 120;
// Upper bounds against typos, not policy: a daily cap in the millions is a slipped key.
const CAP_MAX = 1_000_000;
const TEMPLATE_MAX = 50;
const COMUNAS_MAX = 50;
// A short list read first by someone in danger; more than a handful stops being read.
const EMERGENCY_NUMBERS_MAX = 6;

/**
 * Text per language from the form, `{ es: "Barro", en: "" }`. Blank languages are dropped, so
 * what is stored is exactly what was translated and the admin can show what is missing.
 */
const localizedText = z
  .partialRecord(z.enum(LOCALES), z.string().trim().max(NAME_MAX, { error: "too_long" }))
  .transform((name) => Object.fromEntries(Object.entries(name).filter(([, text]) => text)));

const nameInDefaultLocale = localizedText.refine((name) => Boolean(name[DEFAULT_LOCALE]), {
  error: "name_required",
});

const catalogKey = z.string().trim().regex(KEY_PATTERN, { error: "invalid_key" });
const version = z.int().positive();

const templateItem = z.object({ key: catalogKey, name: nameInDefaultLocale });

const uniqueKeys = (list: { key: string }[]) => new Set(list.map((item) => item.key)).size === list.length;

export const disasterTypeSchema = z.object({
  key: catalogKey,
  name: nameInDefaultLocale,
  workTypes: z
    .array(templateItem)
    .min(1, { error: "work_types_required" })
    .max(TEMPLATE_MAX, { error: "too_many" })
    .refine(uniqueKeys, { error: "duplicate_key" }),
  // Optional: not every disaster needs supplies tracked (ADR 0009, feat/report).
  supplyTypes: z
    .array(templateItem)
    .max(TEMPLATE_MAX, { error: "too_many" })
    .refine(uniqueKeys, { error: "duplicate_key" }),
});
export type DisasterTypeInput = z.infer<typeof disasterTypeSchema>;

export const disasterTypeUpdateSchema = disasterTypeSchema.extend({ version });
export type DisasterTypeUpdate = z.infer<typeof disasterTypeUpdateSchema>;

function isTimeZone(value: string) {
  return Intl.supportedValuesOf("timeZone").includes(value);
}

export const emergencySchema = z
  .object({
    // Generated by the client, so a retry with bad signal never creates a second emergency.
    id: z.uuid(),
    slug: z
      .string()
      .trim()
      .max(SLUG_MAX, { error: "too_long" })
      .regex(SLUG_PATTERN, { error: "invalid_slug" }),
    disasterTypeKey: catalogKey,
    name: localizedText,
    defaultLocale: z.enum(LOCALES),
    timeZone: z.string().refine(isTimeZone, { error: "invalid_time_zone" }),
    comunas: z
      .array(z.string().trim().min(1).max(NAME_MAX, { error: "too_long" }))
      .max(COMUNAS_MAX, { error: "too_many" }),
    // Wall-clock time in the emergency's zone, as a datetime-local field gives it; the database converts it.
    startedAt: z.iso.datetime({ local: true, precision: -1, error: "invalid_date" }),
    area: areaSchema.nullable(),
  })
  .refine((e) => Boolean(e.name[e.defaultLocale]), { error: "name_required", path: ["name"] });
export type EmergencyInput = z.infer<typeof emergencySchema>;

const optionalText = (max: number) =>
  z
    .string()
    .trim()
    .max(max, { error: "too_long" })
    .transform((text) => text || null);
const cap = z
  .int({ error: "invalid_number" })
  .min(0, { error: "invalid_number" })
  .max(CAP_MAX, { error: "invalid_number" });

export const emergencySettingsSchema = z.object({
  emergencyId: z.uuid(),
  version,
  smsDailyCap: cap,
  whatsappDailyCap: cap,
  neighborReserve: cap,
  // Minutes a "Voy para allá" reservation holds (issue #12); the column's CHECK has the same range.
  claimHoldMinutes: z
    .int({ error: "invalid_number" })
    .min(1, { error: "invalid_number" })
    .max(1440, { error: "invalid_number" }),
  // Hours without activity before an open home reads "to confirm" on the map (ADR 0011). A week at
  // most: past that the signal says nothing a coordinator can act on.
  staleAfterHours: z
    .int({ error: "invalid_number" })
    .min(1, { error: "invalid_number" })
    .max(168, { error: "invalid_number" }),
  officialContact: optionalText(200),
  officialSurveyName: optionalText(NAME_MAX),
  emergencyNumbers: z
    .array(
      z.object({
        label: localizedText.refine((label) => Object.keys(label).length > 0, { error: "name_required" }),
        phone: z
          .string()
          .trim()
          .regex(/^\+?[0-9 ]{3,20}$/, { error: "invalid_phone" }),
      }),
    )
    .max(EMERGENCY_NUMBERS_MAX, { error: "too_many" }),
});
export type EmergencySettingsInput = z.infer<typeof emergencySettingsSchema>;

export const emergencyAreaSchema = z.object({ emergencyId: z.uuid(), version, area: areaSchema });
export type EmergencyAreaInput = z.infer<typeof emergencyAreaSchema>;

export const closeEmergencySchema = z.object({ emergencyId: z.uuid() });

const NOTICE_MAX = 500;

export const noticeSchema = z.object({
  emergencyId: z.uuid(),
  // The notice the admin saw when writing this one; null when there was none.
  replacesId: z.uuid().nullable(),
  message: z
    .partialRecord(z.enum(LOCALES), z.string().trim().max(NOTICE_MAX, { error: "too_long" }))
    .transform((text) => Object.fromEntries(Object.entries(text).filter(([, value]) => value)))
    .refine((text) => Object.keys(text).length > 0, { error: "notice_required" }),
});
export type NoticeInput = z.infer<typeof noticeSchema>;

export const noticeWithdrawalSchema = z.object({ emergencyId: z.uuid(), noticeId: z.uuid() });
export type NoticeWithdrawal = z.infer<typeof noticeWithdrawalSchema>;

/** Field errors as `{ "workTypes.2.key": "invalid_key" }`: codes the client translates, never sentences. */
export function fieldErrorsOf(error: z.ZodError): Record<string, string> {
  const errors: Record<string, string> = {};
  for (const issue of error.issues) {
    const path = issue.path.join(".");
    errors[path] ??= /^[a-z_]+$/.test(issue.message) ? issue.message : "invalid";
  }
  return errors;
}

// ArcGIS attribute names: letters, digits and underscores.
const layerField = z
  .string()
  .trim()
  .regex(/^[A-Za-z0-9_]{1,64}$/, { error: "invalid_field" });
const layerFields = z.array(layerField).max(5, { error: "too_many" });

export const officialLayerSchema = z.discriminatedUnion("kind", [
  z.object({
    kind: z.literal("area"),
    emergencyId: z.uuid(),
    layerUrl: z.url({ error: "invalid_layer_url" }),
  }),
  z.object({
    kind: z.literal("worksites"),
    emergencyId: z.uuid(),
    layerUrl: z.url({ error: "invalid_layer_url" }),
    // Joined with spaces into the written address (street, number).
    addressFields: layerFields.min(1, { error: "address_fields_required" }),
    // Kept as "FIELD: value" in the contact notes (a land registry id, for example).
    notesFields: layerFields,
  }),
]);
export type OfficialLayerInput = z.infer<typeof officialLayerSchema>;
